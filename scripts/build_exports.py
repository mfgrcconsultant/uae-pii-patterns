"""Build exports (Purview XML, Forcepoint guide, generic regex) from uae_pii/patterns.yaml.

Run from the repo root:  python scripts/build_exports.py
"""
from __future__ import annotations

import re
import sys
import uuid
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from uae_pii.detectors import load_patterns  # noqa: E402

NS = uuid.UUID("6f1c3a52-9d1e-4b5a-8c7e-2a9e0b7c4d11")  # fixed namespace → stable GUIDs
PURVIEW_LEVEL = {"low": 65, "medium": 75, "high": 85}
BUMP = {65: 75, 75: 85, 85: 85}
ARABIC = re.compile(r"[\u0600-\u06FF]")
HEADER = "<!-- Generated by scripts/build_exports.py from uae_pii/patterns.yaml. Do not edit by hand. -->"


def gid(name: str) -> str:
    return str(uuid.uuid5(NS, name))


def build_purview(cfg: dict) -> str:
    prox = cfg.get("proximity", 300)
    entities, regexes, keywords, strings = [], [], [], []
    for e in cfg["entities"]:
        eid, rid, kid = gid(e["id"]), f"Regex_{e['id']}", f"Keyword_{e['id']}"
        base = PURVIEW_LEVEL[e["confidence"]]
        patterns = [
            f'      <Pattern confidenceLevel="{BUMP[base] if not e["keyword_required"] else base}">\n'
            f'        <IdMatch idRef="{rid}"/>\n        <Match idRef="{kid}"/>\n      </Pattern>'
        ]
        if not e["keyword_required"]:
            patterns.append(f'      <Pattern confidenceLevel="{base}">\n        <IdMatch idRef="{rid}"/>\n      </Pattern>')
        rec = max(BUMP[base], 75) if not e["keyword_required"] else base
        entities.append(
            f'    <Entity id="{eid}" patternsProximity="{prox}" recommendedConfidence="{rec}">\n'
            + "\n".join(patterns) + "\n    </Entity>"
        )
        regexes.append(f'    <Regex id="{rid}">{escape(e["regex"])}</Regex>')
        latin = [k for k in e["keywords"] if not ARABIC.search(k)]
        arabic = [k for k in e["keywords"] if ARABIC.search(k)]
        groups = []
        if latin:
            groups.append('      <Group matchStyle="word">\n' + "\n".join(f"        <Term caseSensitive=\"false\">{escape(k)}</Term>" for k in latin) + "\n      </Group>")
        if arabic:
            groups.append('      <Group matchStyle="string">\n' + "\n".join(f"        <Term>{escape(k)}</Term>" for k in arabic) + "\n      </Group>")
        keywords.append(f'    <Keyword id="{kid}">\n' + "\n".join(groups) + "\n    </Keyword>")
        strings.append(
            f'      <Resource idRef="{eid}">\n'
            f'        <Name default="true" langcode="en-us">{escape(e["name"])}</Name>\n'
            f'        <Description default="true" langcode="en-us">{escape(" ".join(e["description"].split()))}</Description>\n'
            f"      </Resource>"
        )
    return f"""<?xml version="1.0" encoding="utf-8"?>
{HEADER}
<RulePackage xmlns="http://schemas.microsoft.com/office/2011/mce">
  <RulePack id="{gid('rulepack')}">
    <Version major="1" minor="0" build="0" revision="0"/>
    <Publisher id="{gid('publisher')}"/>
    <Details defaultLangCode="en-us">
      <LocalizedDetails langcode="en-us">
        <PublisherName>uae-pii-patterns (community)</PublisherName>
        <Name>UAE PII Sensitive Information Types</Name>
        <Description>Community sensitive information types for UAE identifiers. Test before production use.</Description>
      </LocalizedDetails>
    </Details>
  </RulePack>
  <Rules>
{chr(10).join(entities)}
{chr(10).join(regexes)}
{chr(10).join(keywords)}
    <LocalizedStrings>
{chr(10).join(strings)}
    </LocalizedStrings>
  </Rules>
</RulePackage>
"""


def build_generic(cfg: dict) -> str:
    out = ["<!-- Generated by scripts/build_exports.py. Do not edit by hand. -->",
           "# Generic Regex Reference", "",
           "Copy-paste patterns for any regex-capable tool. They use only common syntax",
           "(fixed-width lookbehind/lookahead), supported by Python, .NET, Java, and PCRE.", "",
           f"Keyword proximity window: **{cfg.get('proximity', 300)} characters**.", ""]
    for e in cfg["entities"]:
        out += [f"## {e['name']}", "",
                " ".join(e["description"].split()), "",
                "```regex", e["regex"], "```", "",
                f"- **Example:** `{e['example']}`",
                f"- **Base confidence:** {e['confidence']}",
                f"- **Validator:** {e.get('validator') or 'none'}",
                f"- **Keyword required:** {'yes' if e['keyword_required'] else 'no'}",
                f"- **Keywords:** {', '.join(e['keywords'])}", ""]
    return "\n".join(out)


def build_forcepoint(cfg: dict) -> str:
    out = ["<!-- Generated by scripts/build_exports.py. Do not edit by hand. -->",
           "# Forcepoint DLP Guidance", "",
           "Forcepoint DLP supports custom **regular-expression** and **key-phrase** content classifiers.",
           "For each identifier below, create both and combine them in a rule. Menu names differ by",
           "version, so follow your console's terminology. Check first whether your version already",
           "ships built-in UAE classifiers.", "",
           "**Recommended approach**", "",
           "1. Create a regular-expression classifier with the pattern below.",
           "2. Create a key-phrase classifier with the keywords (English and Arabic).",
           "3. For identifiers with *keyword required = yes*, the rule should require both classifiers.",
           "4. Start in **monitor/audit mode**, review incidents for false positives, then move to blocking.",
           "5. Validation checks (Luhn, mod-97) are not native regex features. Where your version supports",
           "   scripted classifiers, add them to cut false positives; otherwise rely on keywords and thresholds.", ""]
    for e in cfg["entities"]:
        out += [f"## {e['name']}", "",
                "| Setting | Value |", "|---|---|",
                f"| Regex | `{e['regex'].replace('|', chr(92) + '|')}` |",
                f"| Keywords | {', '.join(e['keywords'])} |",
                f"| Keyword required | {'yes' if e['keyword_required'] else 'no'} |",
                f"| Suggested validator | {e.get('validator') or 'none'} |",
                f"| Suggested starting threshold | {'1 match' if e['confidence'] == 'high' else '3+ matches or keyword present'} |", ""]
    return "\n".join(out)


def main() -> None:
    cfg = load_patterns()
    (ROOT / "exports/purview/uae-pii-rulepack.xml").write_text(build_purview(cfg), encoding="utf-8")
    (ROOT / "exports/forcepoint/README.md").write_text(build_forcepoint(cfg), encoding="utf-8")
    (ROOT / "exports/generic-regex.md").write_text(build_generic(cfg), encoding="utf-8")
    print("Exports written to exports/")


if __name__ == "__main__":
    main()
